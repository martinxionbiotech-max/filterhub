def ref(oe, brand=None, equipment_type=None, status="catalog-confirmed"):
    return {"oe_number": oe, "brand": brand, "equipment_type": equipment_type, "data_status": status}


def spec(key, value, unit=None, status="verified"):
    return {"spec_key": key, "spec_value": value, "unit": unit, "data_status": status}


def mat(part, value, status="catalog-confirmed"):
    return {"part": part, "material_value": value, "data_status": status}


def media(ftype, eff=None, status="catalog-confirmed"):
    return {"type": ftype, "efficiency_class": eff, "grammage": None, "data_status": status}


def app(code, medium, status="reference"):
    return {"code": code, "medium": medium, "data_status": status}


def p(sku, name, category, company, source_url, description=None, data_status="catalog-confirmed",
      efficiency_class=None, subcategory=None, oe_reference=None, spec=None, material=None,
      filter_media=None, application=None, moq=None):
    rec = {
        "sku": sku,
        "name": name,
        "category": category,
        "company": company,
        "description": description,
        "source_url": source_url,
        "data_status": data_status,
        "efficiency_class": efficiency_class,
        "oe_reference": oe_reference or [],
        "spec": spec or [],
        "material": material or [],
        "filter_media": filter_media or [],
        "application": application or [],
        "moq": moq if moq is not None else {"moq_value": None, "moq_unit": None, "data_status": "pending"},
    }
    if subcategory:
        rec["subcategory"] = subcategory
    return rec


